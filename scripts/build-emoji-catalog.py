#!/usr/bin/env python3
"""Pre-shape Unicode 16 emoji against the exact packaged font (host HarfBuzz)."""
import argparse
import ctypes as c
import ctypes.util
from pathlib import Path


def generate(font_path, data_dir, output):
    hb = c.CDLL(ctypes.util.find_library('harfbuzz') or 'libharfbuzz.so.0')
    def api(name, restype, *args):
        fn = getattr(hb, name)
        fn.restype, fn.argtypes = restype, args
        return fn
    ptr, uint = c.c_void_p, c.c_uint
    blob_create = api('hb_blob_create', ptr, c.c_char_p, uint, c.c_int, ptr, ptr)
    face_create = api('hb_face_create', ptr, ptr, uint)
    font_create = api('hb_font_create', ptr, ptr)
    font_funcs = api('hb_ot_font_set_funcs', None, ptr)
    buffer_create = api('hb_buffer_create', ptr)
    add = api('hb_buffer_add_utf8', None, ptr, c.c_char_p, c.c_int, uint, c.c_int)
    guess = api('hb_buffer_guess_segment_properties', None, ptr)
    shape = api('hb_shape', None, ptr, ptr, ptr, uint)
    class Info(c.Structure):
        _fields_ = [(name, uint) for name in ('glyph', 'mask', 'cluster', 'var1', 'var2')]
    infos = api('hb_buffer_get_glyph_infos', c.POINTER(Info), ptr, c.POINTER(uint))
    reset = api('hb_buffer_reset', None, ptr)
    font_bytes = Path(font_path).read_bytes()
    blob = blob_create(font_bytes, len(font_bytes), 0, None, None)
    face = face_create(blob, 0)
    font = font_create(face)
    font_funcs(font)
    buffer = buffer_create()
    records, group = [], -1
    for line in (data_dir / 'emoji-test.txt').read_text().splitlines():
        if line.startswith('# group:') and line != '# group: Component':
            group += 1
        if not line or line.startswith('#'):
            continue
        codes, tail = line.split(';')
        status = tail.split('#')[0].strip()
        text = ''.join(chr(int(code, 16)) for code in codes.split())
        encoded = text.encode()
        reset(buffer)
        add(buffer, encoded, len(encoded), 0, len(encoded))
        guess(buffer)
        shape(font, buffer, None, 0)
        count = uint()
        result = infos(buffer, c.byref(count))
        # A fully assembled, non-.notdef glyph is required; components never enter the picker.
        if count.value == 1 and result[0].glyph:
            records.append((text, result[0].glyph, group, status == 'fully-qualified'))
    for kind, obj in [('buffer', buffer), ('font', font), ('face', face), ('blob', blob)]:
        api('hb_' + kind + '_destroy', None, ptr)(obj)
    records.sort(key=lambda record: record[0].encode())
    full = {text: i for i, (text, _, _, qualified) in enumerate(records) if qualified}
    def root(text):
        return ''.join(ch for ch in text if ord(ch) != 0xfe0f and not 0x1f3fb <= ord(ch) <= 0x1f3ff)
    roots = {}
    for text, i in full.items():
        key = root(text)
        if key not in roots or not any(0x1f3fb <= ord(ch) <= 0x1f3ff for ch in text):
            roots[key] = i
    counts = {}
    for text in full:
        base = roots[root(text)]
        counts[base] = counts.get(base, 0) + 1
    def literal(text):
        return '"' + ''.join('\\x%02x' % byte for byte in text.encode()) + '"'
    lines = ['// Generated by scripts/build-emoji-catalog.py; Unicode 16.0 + the packaged Noto font.',
             '#pragma once', '#include <cstdint>', 'namespace emoji_data {',
             'struct Entry { const char* text; uint16_t glyph, base; uint8_t group; bool picker, variants; };',
             'inline constexpr Entry entries[] = {']
    for i, (text, glyph, group, qualified) in enumerate(records):
        base = roots.get(root(text), i)
        lines.append('    {%s, %d, %d, %d, %s, %s},' % (literal(text), glyph, base, group, str(qualified).lower(), str(counts.get(base, 0) > 1).lower()))
    lines += ['};', 'struct Range { uint32_t first, last; uint8_t property; };',
              'enum Property { Other, CR, LF, Control, Extend, ZWJ, Regional_Indicator, Prepend, SpacingMark, L, V, T, LV, LVT };',
              'inline constexpr Range breaks[] = {']
    ranges = []
    for line in (data_dir / 'GraphemeBreakProperty.txt').read_text().splitlines():
        content = line.split('#')[0].strip()
        if content:
            span, prop = map(str.strip, content.split(';'))
            ends = span.split('..')
            ranges.append((int(ends[0], 16), int(ends[-1], 16), prop))
    for first, last, prop in sorted(ranges):
        lines.append('    {0x%x, 0x%x, %s},' % (first, last, prop))
    lines += ['};', 'inline constexpr Range pictographs[] = {']
    for line in (data_dir / 'emoji-data.txt').read_text().splitlines():
        content = line.split('#')[0].strip()
        if content:
            span, prop = map(str.strip, content.split(';'))
            if prop == 'Extended_Pictographic':
                ends = span.split('..')
                lines.append('    {0x%s, 0x%s, 0},' % (ends[0], ends[-1]))
    lines += ['};', '}']
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines) + '\n')
    print('Emoji catalog: %d supported sequences, %d picker entries' % (len(records), len(full)))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('font', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    generate(args.font, Path(__file__).resolve().parent / 'unicode/16.0', args.output)
